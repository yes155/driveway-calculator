export function RepairReference() {
  const items = [
    ['Asphalt crack filling', 'asphaltCrackFill'],
    ['Asphalt hot patch', 'asphaltHotPatch'],
    ['Pothole repair', 'asphaltPothole'],
    ['Concrete crack filling', 'concrete.crackRepair'],
    ['Concrete resurfacing', 'concrete.resurfacing'],
  ];
  const rows = items.map(([label, item]) => {
    const d = research.decisions.find((d) => d.item === item)!;
    const source = sources.find((s) => s.id === d.sourceIds[0])!;
    return [
      label,
      `${rateMoney(d.selectedLow!)}–${rateMoney(d.selectedHigh!)}`,
      d.unit,
      source.name,
    ];
  });
  return (
    <section className="reference-panel">
      <h2>Which repair units belong in the quote?</h2>
      <p>
        <strong>
          Crack length, patch area, and whole-job charges measure different repair scopes.
        </strong>{' '}
        These named published benchmarks remain separate; minimum service charges and structural
        correction need a local quote.
      </p>
      <div className="table-scroll">
        <table>
          <caption>Method-specific repair references · retrieved October 12, 2026</caption>
          <thead>
            <tr>
              <th>Method</th>
              <th>Published range</th>
              <th>Unit</th>
              <th>Source</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => (
              <tr key={r[0]}>
                {r.map((v, i) => (i === 0 ? <th key={i}>{v}</th> : <td key={i}>{v}</td>))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <p>
        Do not multiply crack-filling rates by whole driveway square footage or convert a per-job
        pothole charge without its repair dimensions.
      </p>
    </section>
  );
}
