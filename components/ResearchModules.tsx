const names: Record<string, string> = {
  asphalt: 'New asphalt',
  concrete: 'Standard concrete',
  'stamped-concrete': 'Basic stamped concrete',
  gravel: 'Gravel',
  pavers: 'Pavers',
  'tar-and-chip': 'Tar and chip',
  slab: 'Flat slab',
  sealcoating: 'Sealcoating',
  millings: 'Millings',
  overlay: 'Asphalt overlay',
  'asphalt-replacement': 'Asphalt replacement',
  'concrete-replacement': 'Concrete replacement',
  repair: 'Asphalt hot patch',
  'concrete-repair': 'Concrete resurfacing',
};
export function CostReference({ surface }: { surface: string }) {
  const p = priceBook[surface];
  const low = verifiedValue(p?.installedLow),
    high = verifiedValue(p?.installedHigh);
  if (low === null || high === null)
    return <p>Pricing for this scope remains unavailable. Use an itemized local quote.</p>;
  const sample = computeCost({ area: 400, unit: { low, high }, tier: 1, extras: [] })!;
  return (
    <section className="reference-panel">
      <h2>Which published range does the estimate use?</h2>
      <p>
        <strong>
          {names[surface] ?? surface}: {rateMoney(low)}–{rateMoney(high)} per square foot.
        </strong>{' '}
        {surface === 'concrete-replacement' ? (
          'This range is derived from the separate installation and demolition components; it is not an observed replacement quote.'
        ) : (
          <>
            This named benchmark is preserved from {p.installedLow.source}; competing guides are not
            averaged.
          </>
        )}
      </p>
      <div className="table-scroll">
        <table>
          <caption>Published rate and an illustrative measurement</caption>
          <thead>
            <tr>
              <th>Basis</th>
              <th>Low</th>
              <th>High</th>
            </tr>
          </thead>
          <tbody>
            <tr>
              <th>Installed work / ft²</th>
              <td>{rateMoney(low)}</td>
              <td>{rateMoney(high)}</td>
            </tr>
            <tr>
              <th>20 × 20 ft example · 400 ft²</th>
              <td>{money(sample.low)}</td>
              <td>{money(sample.high)}</td>
            </tr>
          </tbody>
        </table>
      </div>
      <p>
        The example is generated by the cost engine with no regional adjustment or additional
        charges. Site conditions, work inclusions, and local quotes determine the project total.{' '}
        {surface.includes('replacement')
          ? 'Removal is included in this replacement basis; do not add it twice.'
          : 'Add separately quoted work only when excluded from the installed scope.'}
      </p>
      <p className="source-caption">
        Retrieved {p.installedLow.retrievedOn}. Source comparisons and exclusions:{' '}
        <Link href="/methodology/">Methodology</Link>.
      </p>
    </section>
  );
}
export function SurfaceComparison({ pairOnly = false }: { pairOnly?: boolean }) {
  const allKeys = ['asphalt', 'concrete', 'stamped-concrete', 'gravel', 'pavers', 'tar-and-chip'];
  const keys = pairOnly ? ['asphalt', 'concrete'] : allKeys;
  const rows = computeCompare(
    400,
    1,
    keys.map((name) => {
      const p = priceBook[name];
      return {
        name,
        unit: { low: p.installedLow.value!, high: p.installedHigh.value! },
        lifespan:
          p.lifespanLow.value !== null && p.lifespanHigh.value !== null
            ? { low: p.lifespanLow.value, high: p.lifespanHigh.value }
            : null,
        extras: [],
        upkeep: [],
      };
    }),
  ).rows;
  return (
    <section className="reference-panel">
      <h2>How do published surface ranges compare?</h2>
      <p>
        <strong>Compare the same measured area and the same included work.</strong> These are
        different publishers’ benchmarks, not local bids collected for one project.
      </p>
      <div className="table-scroll">
        <table>
          <caption>400 ft² illustrative comparison · no extras or regional adjustment</caption>
          <thead>
            <tr>
              <th>Surface</th>
              <th>Installed / ft²</th>
              <th>400 ft² example</th>
              <th>Service-life reference</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => (
              <tr key={r.name}>
                <th>{names[r.name]}</th>
                <td>
                  {rateMoney(priceBook[r.name].installedLow.value!)}–
                  {rateMoney(priceBook[r.name].installedHigh.value!)}
                </td>
                <td>
                  {money(r.low)}–{money(r.high)}
                </td>
                <td>
                  {r.lifespan
                    ? `${r.lifespan.low}–${r.lifespan.high} years`
                    : 'No comparable bounded range'}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <p>
        Service life depends on construction and maintenance. Upfront cost divided by service life
        excludes maintenance, financing, and future replacement. Gravel remains renewable through
        replenishment, so a fixed life denominator is omitted.
      </p>
    </section>
  );
}
export function MaterialReferences({ material }: { material?: string }) {
  const allKeys = [
    'asphaltDensity',
    'rockDensity',
    'peaGravelDensity',
    'crusherRunDensity',
    'roadBaseDensity',
    'concreteDensity',
  ];
  const selection: Record<string, string[]> = {
    asphalt: ['asphaltDensity'],
    millings: ['millingsBulkDensity'],
    gravel: ['crushedStoneDensity'],
    layers: ['roadBaseDensity', 'crushedStoneDensity'],
    rock: ['rockDensity'],
    pea: ['peaGravelDensity'],
    crusher: ['crusherRunDensity'],
    base: ['roadBaseDensity'],
    concrete: ['concreteDensity'],
  };
  const keys = material && selection[material] ? selection[material] : allKeys;
  return (
    <section className="reference-panel">
      <h2>Which material density references are available?</h2>
      <p>
        <strong>Density follows the named material and its condition.</strong> Loose stockpile,
        compacted paving, and cured concrete values describe different volumes.
      </p>
      <div className="table-scroll">
        <table>
          <caption>Named editable material references</caption>
          <thead>
            <tr>
              <th>Reference</th>
              <th>Value</th>
              <th>Source and scope</th>
            </tr>
          </thead>
          <tbody>
            {keys.map((k) => {
              const d = defaultBook[k];
              return (
                <tr key={k}>
                  <th>{k.replace(/([A-Z])/g, ' $1')}</th>
                  <td>
                    {number(d.value!)} {d.unit}
                  </td>
                  <td>
                    {d.source}. {d.scope}
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
      <p>
        Replace a reference with the density supplied for your order. Moisture, size grading, voids,
        and compaction change bulk density.{' '}
        <Link href="/material-weights/">Material Weight Chart</Link> connects these inputs to the
        quantity tools.
      </p>
    </section>
  );
}
export function WeightReference({ material }: { material: 'concrete' | 'gravel' }) {
  const density =
    material === 'concrete'
      ? defaultBook.concreteDensity.value!
      : (defaultBook.crushedStoneDensity.value! * 2000) / 27;
  const weight = computeConversion({
    amount: 1,
    density: (density * 27) / 2000,
    direction: 'yards-to-tons',
  });
  return (
    <section className="reference-panel">
      <h2>How does density determine weight per cubic yard?</h2>
      <p>
        <strong>Weight per cubic yard equals density per cubic foot × 27.</strong> At the named{' '}
        {material === 'concrete'
          ? 'NRMCA normalweight reference'
          : 'Two Rivers 5/8-inch crushed-stone reference'}
        , one cubic yard is {number(weight.tons * 2000)} lb, or {number(weight.tons)} US short tons.
      </p>
      <p>
        The result is calculated from the selected reference. Dry bagged concrete, cured
        normalweight concrete, lightweight concrete, and loose crushed concrete are separate
        materials. Supplier-specific gravel density replaces a universal weight assumption.
      </p>
    </section>
  );
}
